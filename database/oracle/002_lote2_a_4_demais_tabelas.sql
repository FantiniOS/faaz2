  CONSTRAINT FK_CONSULT_ORG FOREIGN KEY (ORGANIZATION_ID) REFERENCES ORGANIZATIONS (ID),
  CONSTRAINT FK_CONSULT_PATIENT FOREIGN KEY (PATIENT_ID) REFERENCES PATIENTS (ID),
  CONSTRAINT FK_CONSULT_PROF FOREIGN KEY (PROFESSIONAL_ID) REFERENCES USERS (ID),
  CONSTRAINT FK_CONSULT_PARENT FOREIGN KEY (PARENT_CONSULTATION_ID) REFERENCES CONSULTATIONS (ID),
  CONSTRAINT CK_CONSULT_EVENT_TYPE CHECK (EVENT_TYPE IN (
    'ROUTINE_CONSULTATION', 'NUTRITION_EVALUATION', 'LAB_REVIEW', 'CLINICAL_ADDENDUM')),
  CONSTRAINT CK_CONSULT_STATUS CHECK (STATUS IN (
    'DRAFT', 'FINALIZED', 'SUPERSEDED', 'ANNULLED_WITH_JUSTIFICATION'))
