  VERSION_NUMBER          NUMBER(10)                   DEFAULT 1 NOT NULL,
  EVENT_TYPE              VARCHAR2(30 CHAR)            NOT NULL,
  CONSULTATION_DATE       TIMESTAMP(6) WITH TIME ZONE  NOT NULL,
  SOAP_SUBJECTIVE         CLOB,
  SOAP_OBJECTIVE          CLOB,
  SOAP_ASSESSMENT         CLOB,
  SOAP_PLAN               CLOB,
