-- Evolução aditiva da prescrição dietética clínica real + check-in leve:
--   1. REFEICOES.OPCIONAL (NUMBER(1) DEFAULT 0 NOT NULL)
--      (REFEICOES.OBSERVACOES CLOB já existe desde o Lote 2)
--   2. ITENS_REFEICOES.MEDIDA_CASEIRA (VARCHAR2(120 CHAR))
--      ITENS_REFEICOES.UNIDADE (VARCHAR2(16 CHAR) DEFAULT 'g' NOT NULL)
--   3. SUBSTITUICOES_ITENS_REFEICAO (substituições prescritas 1:N por item)
--   4. CHECKINS_REFEICOES (check-in leve de refeição pelo app mobile)
-- ============================================================================

-- 1. REFEICOES: sinalização de refeição opcional (ex.: Ceia OPCIONAL)
ALTER TABLE REFEICOES ADD (
  OPCIONAL NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT CK_REFEICOES_OPCIONAL CHECK (OPCIONAL IN (0, 1))
);

-- 2. ITENS_REFEICOES: medida caseira e unidade (g / ml / un)
ALTER TABLE ITENS_REFEICOES ADD (
  MEDIDA_CASEIRA VARCHAR2(120 CHAR),
  UNIDADE        VARCHAR2(16 CHAR) DEFAULT 'g' NOT NULL,
  CONSTRAINT CK_ITENS_REF_UNIDADE CHECK (UNIDADE IN ('g', 'ml', 'un'))
);

-- 3. SUBSTITUICOES_ITENS_REFEICAO (Opções de troca 1:N prescritas pela médica)
CREATE TABLE SUBSTITUICOES_ITENS_REFEICAO (
  ID                VARCHAR2(36 CHAR)            NOT NULL,
  ITEM_REFEICAO_ID  VARCHAR2(36 CHAR)            NOT NULL,
  ALIMENTO_ID       VARCHAR2(36 CHAR),
  NOME_EXIBICAO     VARCHAR2(200 CHAR)           NOT NULL,
  QUANTIDADE        BINARY_DOUBLE                DEFAULT 100 NOT NULL,
  UNIDADE           VARCHAR2(16 CHAR)            DEFAULT 'g' NOT NULL,
  MEDIDA_CASEIRA    VARCHAR2(120 CHAR),
  ORDEM             NUMBER(10)                   DEFAULT 1 NOT NULL,
  CREATED_AT        TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT        TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_SUB_ITENS_REF PRIMARY KEY (ID),
  CONSTRAINT FK_SUB_ITENS_REF_ITEM
    FOREIGN KEY (ITEM_REFEICAO_ID) REFERENCES ITENS_REFEICOES (ID) ON DELETE CASCADE,
  CONSTRAINT FK_SUB_ITENS_REF_ALIM
    FOREIGN KEY (ALIMENTO_ID) REFERENCES ALIMENTOS (ID) ON DELETE SET NULL,
  CONSTRAINT CK_SUB_ITENS_REF_UNIDADE CHECK (UNIDADE IN ('g', 'ml', 'un'))
);

CREATE INDEX IX_SUB_ITENS_REF_ITEM_ORDEM
  ON SUBSTITUICOES_ITENS_REFEICAO (ITEM_REFEICAO_ID, ORDEM);

-- 4. CHECKINS_REFEICOES (Check-in leve de 3 segundos no app mobile)
CREATE TABLE CHECKINS_REFEICOES (
  ID               VARCHAR2(36 CHAR)            NOT NULL,
  PACIENTE_ID      VARCHAR2(36 CHAR)            NOT NULL,
  REFEICAO_ID      VARCHAR2(36 CHAR)            NOT NULL,
  DATA_DIA         VARCHAR2(10 CHAR)            NOT NULL,
  STATUS           VARCHAR2(20 CHAR)            NOT NULL,
  OPCAO_ESCOLHIDA  VARCHAR2(120 CHAR),
  TROCAS_JSON      CLOB,
  CRIADO_EM        TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,
  ATUALIZADO_EM    TIMESTAMP(6) WITH TIME ZONE  DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT PK_CHECKINS_REFEICOES PRIMARY KEY (ID),
  CONSTRAINT UQ_CHECKINS_REF_PAC_DIA UNIQUE (PACIENTE_ID, REFEICAO_ID, DATA_DIA),
  CONSTRAINT FK_CHECKIN_REF_PATIENT
    FOREIGN KEY (PACIENTE_ID) REFERENCES PATIENTS (ID) ON DELETE CASCADE,
  CONSTRAINT FK_CHECKIN_REF_REFEICAO
    FOREIGN KEY (REFEICAO_ID) REFERENCES REFEICOES (ID) ON DELETE CASCADE,
  CONSTRAINT CK_CHECKIN_REF_STATUS CHECK (STATUS IN ('SEGUI', 'FIZ_TROCA', 'NAO_FIZ')),
  CONSTRAINT CK_CHECKIN_REF_TROCAS_JSON CHECK (TROCAS_JSON IS NULL OR TROCAS_JSON IS JSON)
);

CREATE INDEX IX_CHECKINS_REF_PAC_DIA
  ON CHECKINS_REFEICOES (PACIENTE_ID, DATA_DIA DESC);
